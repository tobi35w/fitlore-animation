import fs from 'node:fs';
import path from 'node:path';
import { ensureDir, readJson, resolve, safeSlug, writeJson } from './runtime.mjs';
import { defaultVoice } from './elevenlabs.mjs';

export function updateRegistry() {
  const folders = fs.readdirSync(ensureDir(resolve('projects')), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(resolve('projects', entry.name, 'project.json')))
    .map((entry) => entry.name).sort();
  const imports = ["// Generated by scripts/projects.mjs. Edit each project's source and project.json.", "import type { ProjectEntry } from './types';"];
  const entries = [];
  for (const [index, slug] of folders.entries()) {
    safeSlug(slug);
    if (readJson(resolve('projects', slug, 'project.json')).builtIn) continue;
    imports.push(`import { Video as Video${index} } from './videos/${slug}/index';`);
    imports.push(`import config${index} from '../projects/${slug}/project.json';`);
    entries.push(`  { id: config${index}.id, component: Video${index}, durationInFrames: config${index}.durationInFrames, fps: config${index}.fps, width: config${index}.width, height: config${index}.height, audioFile: config${index}.audioFile }`);
  }
  fs.writeFileSync(resolve('src/project-registry.ts'), imports.join('\n') + '\nexport const projects: ProjectEntry[] = [\n' + entries.join(',\n') + '\n];\n');
}

export function createProject(slug, { setupTest = false } = {}) {
  safeSlug(slug);
  const directory = resolve('projects', slug);
  const source = resolve('src/videos', slug);
  if (fs.existsSync(directory) || fs.existsSync(source)) throw new Error(`Project ${slug} already exists; its files were left intact.`);
  const id = slug.split('-').map((word) => word[0].toUpperCase() + word.slice(1)).join('');
  if (['BridgeShort', 'WorkflowCheck', 'Bridge'].includes(id)) throw new Error(`${slug} is reserved for the example or checks.`);
  ensureDir(directory);
  ensureDir(source);
  ensureDir(resolve('public/projects', slug));
  writeJson(path.join(directory, 'project.json'), { id, slug, fps: 30, width: 1080, height: 1920,
    durationInFrames: 120, audioFile: null, ...defaultVoice, setupTest });
  fs.writeFileSync(path.join(directory, 'brief.md'), `# ${id}\n\nStatus: awaiting a video brief.\n\nRecord the topic, audience, factual sources, visual direction, and requested length here.\n`);
  fs.writeFileSync(path.join(directory, 'narration.txt'), '');
  writeJson(path.join(directory, 'sound.json'), { targetLufs: -16, music: { enabled: true, bpm: 96, gainDb: -10, duckDb: -7 }, sfx: [] });
  writeJson(path.join(directory, 'shots.json'), { shots: [], planned: [], xfade: [] });
  fs.writeFileSync(path.join(source, 'index.tsx'), "// Replace the starter with this project's story visuals.\nexport { Starter as Video } from '../../Starter';\n");
  updateRegistry();
  console.log(`Created ${directory} (composition ${id}).`);
  return directory;
}

export function findProjectByComposition(id) {
  for (const entry of fs.readdirSync(ensureDir(resolve('projects')), { withFileTypes: true })) {
    const file = resolve('projects', entry.name, 'project.json');
    if (entry.isDirectory() && fs.existsSync(file)) {
      const config = readJson(file);
      if (config.id === id) return { config, file, slug: entry.name };
    }
  }
  return null;
}
